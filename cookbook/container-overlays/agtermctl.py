#!/usr/bin/env python3
"""
agtermctl — in-container agterm overlay forwarder for docker.

Installed as `agtermctl` inside the container, it rewrites the two overlay
subcommands so they work from there; every other call is forwarded to the
real agtermctl on the Mac through a small receiver (agtermctl-receiver.py),
which streams stdout, stderr and the exit code back:

  COMMAND        → structured exec request: the receiver builds the
                    docker-exec line ON THE MAC, from its own template and
                    the request's ingredients (container, base64 payload,
                    open flags) — the program runs IN the container, in the
                    caller's cwd (or --cwd when given). No caller-written
                    shell line ever crosses the wire.
  --html FILE    → FILE translated to a Mac path via the bind map
                    (bind-map.json, generated by bind-map.py from
                    `docker inspect`). Files not under any bind are staged:
                    the file's parent tree is copied (capped) into
                    <staging>/<uuid>/ and the Mac twin of the copy is
                    passed. A --cwd grant is ALWAYS synthesized — without it
                    agterm loads the page via loadHTMLString at about:blank
                    with zero file access (no relative assets).
  --url URL      → container-loopback URLs (localhost/127.0.0.1/::1 or
                    /etc/hosts names mapped to 127.0.0.1) are rewritten via
                    the expose command. With docker, publishing happened at
                    `docker run -p`, so the default expose is the identity
                    script agt-ovl-expose; AGT_OVL_EXPOSE="" passes every
                    --url through unrewritten. Every parsed URL open —
                    rewritten or not — carries the caller's --target.
  reload         → all live staged entries are re-copied from their sources
                    first, then the reload passes through (agterm re-reads
                    disk for --cwd pages; the wrapper owns the staging map).

Parsing rule (agterm ≥ 0.39.0): `session overlay open` has a CLOSED flag
surface, and flags parse before AND after the COMMAND positional (the host
CLI accepts both orders). An unparsable call carrying --html/--url passes
through unrewritten — the host may know a newer flag. Any other unparsable
open dies here: sent as-is it would run its COMMAND on the Mac. Everything
else (any other subcommand) passes through byte-identical.

Portable by design: every machine fact enters via AGT_OVL_* env vars with
docker defaults; no hostnames, users or paths beyond the bridge layout this
recipe's Setup creates. Python 3 stdlib only.
"""

