# --- Defaults / inputs ------------------------------------------------------

RECEIVER_HOST = os.environ.get("AGT_OVL_HOST", "host.docker.internal")
RECEIVER_PORT = int(os.environ.get("AGT_OVL_PORT", "59998"))
CONTAINER_SOURCE = os.environ.get("AGT_OVL_CONTAINER_SOURCE", "hostname")
BIND_MAP_SOURCE = os.environ.get("AGT_OVL_BIND_MAP_SOURCE", "/agterm-bridge/bind-map.json")
# Expose command: "<cmd> <port>" must print the stable contract line
# `exposed <container_port> on 127.0.0.1:<host_port>` and be idempotent.
# AGT_OVL_EXPOSE="" (empty) DISABLES URL rewriting — every --url passes
# through verbatim (for setups whose port publishing already puts the
# container port on the Mac's localhost, or readers who want zero magic).
EXPOSE_CMD = os.environ.get("AGT_OVL_EXPOSE", "agt-ovl-expose")
STAGING_ROOT = os.environ.get("AGT_OVL_STAGING", "/agterm-bridge/pages")
STAGING_MAX_FILES = int(os.environ.get("AGT_OVL_STAGING_MAX_FILES", "200"))
STAGING_MAX_BYTES = int(os.environ.get("AGT_OVL_STAGING_MAX_BYTES", str(20 * 1024 * 1024)))
STAGING_TTL = int(os.environ.get("AGT_OVL_STAGING_TTL", str(24 * 3600)))

# The stable reply line of the expose command (the parse contract).
EXPOSE_LINE_RE = re.compile(r"^exposed\s+(\d+)\s+on\s127\.0\.0\.1:(\d+)\s*$", re.MULTILINE)

# agterm ≥ 0.39.0 `session overlay open` flag inventory (keep synced with
# agterm releases; unknown flags force passthrough or die, see parse_open).
VALUE_FLAGS = {
    "--html", "--url", "--cwd", "--size-percent", "--width", "--height",
    "--background-color", "--pane", "--target", "--window", "--socket",
}
BOOL_FLAGS = {
    "--wait", "--block", "--follow", "--navigation", "--js", "--chromeless",
    "--persistent", "--browse", "--companion", "--json",
}

LOOPBACK_HOSTS = {"localhost", "127.0.0.1", "::1"}


def debug(msg):
    """Emit a trace line when AGT_OVL_DEBUG=1 (verification aid)."""
    if os.environ.get("AGT_OVL_DEBUG") == "1":
        sys.stderr.write(f"agtermctl-wrapper: {msg}\n")
        sys.stderr.flush()


def die(msg) -> NoReturn:
    sys.stderr.write(f"agtermctl: {msg}\n")
    sys.stderr.flush()
    sys.exit(1)


# --- Bind map / identity ----------------------------------------------------

def load_info():
    """Load {bind_map, store_roots} from AGT_OVL_BIND_MAP_SOURCE. None on failure."""
    try:
        with open(BIND_MAP_SOURCE, "r", encoding="utf-8") as f:
            info = json.load(f)
        bind_map = info.get("bind_map") or {}
        store_roots = info.get("store_roots") or []
        if not isinstance(bind_map, dict) or not isinstance(store_roots, list):
            return None
        return {"bind_map": bind_map, "store_roots": store_roots}
    except (OSError, ValueError):
        return None


def container_name():
    """Resolve the container name via AGT_OVL_CONTAINER_SOURCE (a command)."""
    try:
        out = subprocess.run(
            shlex.split(CONTAINER_SOURCE),
            capture_output=True, text=True, timeout=10, check=True,
        )
        return out.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None


def is_prefix(prefix, path):
    """Component-wise path prefix: /a/b matches /a/b/c but not /a/bx."""
    return path == prefix or path.startswith(prefix + "/")


def translate(bind_map, path):
    """Longest component-wise prefix translation; None when no host twin."""
    best = None
    for key in bind_map:
        if is_prefix(key, path) and (best is None or len(key) > len(best)):
            best = key
    if best is None:
        return None
    return bind_map[best] + path[len(best):]


def load_hosts_loopback(etc_hosts="/etc/hosts"):
    """Names /etc/hosts maps to 127.0.0.1."""
    names = set()
    try:
        with open(etc_hosts, "r", encoding="utf-8") as f:
            for line in f:
                line = line.split("#", 1)[0].split()
                if len(line) >= 2 and line[0] == "127.0.0.1":
                    names.update(n for n in line[1:] if n)
    except OSError:
        pass
    return names


# --- argv parsing -----------------------------------------------------------

class OpenCall:
    """Parsed `session overlay open` argv with substitution positions."""

    def __init__(self):
        self.values: dict = {}   # flag name → value (last occurrence wins)
        self.bools: set = set()
        self.subst: dict = {}    # token index to rewrite: flag name → value-token idx
        self.command_idx = None  # COMMAND's token index, None when absent
        self.eq_form: set = set()  # flags given as --flag=value (subst replaces whole token)


def parse_open(tokens):
    """Parse open's tokens per the closed flag surface. None ⇒ unparsable.

    Flags parse before AND after the COMMAND positional (the host CLI
    accepts both orders); `--` ends flag scanning; a second positional, an
    unknown flag, a repeated value flag, `--bool=x` or a missing value is
    unparsable.
    """
    call = OpenCall()
    i = 0
    n = len(tokens)
    while i < n:
        tok = tokens[i]
        if tok == "--":
            i += 1
            break
        if tok.startswith("--"):
            name, eq, val = tok.partition("=")
            if name in VALUE_FLAGS:
                if name in call.values:
                    return None  # repeated value flag — the host CLI keeps the last occurrence
                if eq:
                    call.values[name] = val
                    call.subst[i] = name
                    call.eq_form.add(i)
                else:
                    if i + 1 >= n:
                        return None  # missing value — let the host CLI error
                    call.values[name] = tokens[i + 1]
                    call.subst[i + 1] = name
                    i += 1
            elif name in BOOL_FLAGS:
                if eq:
                    return None  # boolean with =value is malformed
                call.bools.add(name)
            else:
                return None  # unknown flag — never guess
        else:
            if call.command_idx is not None:
                return None  # agterm takes exactly one COMMAND positional
            call.command_idx = i
        i += 1
    # Everything after a seen `--` is positional too.
    while i < n:
        if call.command_idx is not None:
            return None
        call.command_idx = i
        i += 1
    return call


def _has_page_flag(tokens):
    """Whether any token names --html/--url (eq form included)."""
    return any(
        t in ("--html", "--url") or t.startswith(("--html=", "--url="))
        for t in tokens
    )


def find_route(argv, route):
    """Locate `route` (e.g. ['session','overlay','open']) with only flags
    before it. Returns (tokens_base, rest) where tokens_base is the argv
    index where `rest` begins, or (None, None) when not found. All
    parse_open indices are relative to `rest` — always add tokens_base
    before touching argv."""
    end = argv.index("--") if "--" in argv else len(argv)
    for i in range(min(end, len(argv)) - len(route) + 1):
        if argv[i:i + len(route)] == route:
            if all(t.startswith("-") for t in argv[:i]):
                return i + len(route), argv[i + len(route):]
            return None, None
    return None, None


# --- Rewrites ----------------------------------------------------------------

def sh_quote_single(s):
    """POSIX single-quote escaping (host sh eval + inner sh safe)."""
    return "'" + s.replace("'", "'\\''") + "'"


def build_payload(cwd, command):
    """The container-side payload: cd into cwd, run COMMAND."""
    return f"cd {sh_quote_single(cwd)} && {command}"


def slice_open_flags(tokens, command_idx):
    """Open flags sliced verbatim from parsed tokens: drops the COMMAND
    positional, the `--` separator and the --cwd pair in both forms (the
    container cwd belongs in the payload, never on the Mac). Order and
    --flag=val forms survive exactly; the caller appends its --target.
    Never rebuild from OpenCall's values/bools — bools is a set and eq
    forms would not survive."""
    flags = []
    i = 0
    n = len(tokens)
    while i < n:
        if i == command_idx:
            i += 1
            continue
        tok = tokens[i]
        if tok == "--" or tok.startswith("--cwd="):
            i += 1
            continue
        if tok == "--cwd":
            i += 2
            continue
        flags.append(tok)
        if tok in VALUE_FLAGS:  # bare value flag — its value follows verbatim
            i += 1
            flags.append(tokens[i])
        i += 1
    return flags


def decide_html(file_abs, cwd_abs, bind_map, store_roots):
    """('direct', host_file, host_cwd) or ('stage', file_abs, cwd_abs)."""
    host_file = translate(bind_map, file_abs)
    in_store = any(is_prefix(r, file_abs) for r in store_roots)
    if host_file is not None and not in_store:
        host_cwd = None
        if cwd_abs:
            host_cwd = translate(bind_map, cwd_abs)
            if host_cwd is None or any(is_prefix(r, cwd_abs) for r in store_roots):
                host_cwd = None
        if host_cwd is None:
            host_cwd = os.path.dirname(host_file)
        return ("direct", host_file, host_cwd)
    return ("stage", file_abs, cwd_abs)


def copy_tree_capped(src_dir, dst_dir, max_files, max_bytes):
    """Copy src_dir's tree into dst_dir. Returns False (nothing copied) when
    the scan exceeds the caps — caller falls back to file-only copy."""
    entries = []
    total = 0
    for root, dirs, files in os.walk(src_dir):
        dirs.sort()
        for name in sorted(files):
            p = os.path.join(root, name)
            try:
                size = os.path.getsize(p)
            except OSError:
                size = 0
            entries.append((p, os.path.relpath(p, src_dir)))
            total += size
            if len(entries) > max_files or total > max_bytes:
                return False
    os.makedirs(dst_dir, exist_ok=True)
    for p, rel in entries:
        dst = os.path.join(dst_dir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        try:
            shutil.copy2(p, dst)
        except OSError:
            pass  # best-effort: unreadable sibling must not kill the page
    return True


def manifest_path(staging_root):
    return os.path.join(staging_root, "manifest.json")


def load_manifest(staging_root):
    try:
        with open(manifest_path(staging_root), "r", encoding="utf-8") as f:
            m = json.load(f)
        return m if isinstance(m, dict) else {}
    except (OSError, ValueError):
        return {}


def save_manifest(staging_root, manifest):
    os.makedirs(staging_root, exist_ok=True)
    tmp = manifest_path(staging_root) + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
    os.replace(tmp, manifest_path(staging_root))


def gc_staging(staging_root, ttl, now):
    """Prune manifest entries older than ttl (dir mtime); a missing dir
    drops its entry. Never touches anything the manifest does not list —
    the staging root may be a directory the reader shares. Best-effort."""
    manifest = load_manifest(staging_root)
    changed = False
    for name in list(manifest):
        path = os.path.join(staging_root, name)
        if not os.path.isdir(path):
            manifest.pop(name, None)
            changed = True
            continue
        try:
            if now - os.path.getmtime(path) <= ttl:
                continue
            shutil.rmtree(path, ignore_errors=True)
        except OSError:
            continue
        manifest.pop(name, None)
        changed = True
    if changed:
        save_manifest(staging_root, manifest)


def stage_page(staging_root, bind_map, file_abs, max_files, max_bytes, now):
    """Copy file's parent tree into <staging>/<uuid>/. Returns the pair of
    CONTAINER paths to hand to agterm: (staged_file, staged_cwd)."""
    host_root = translate(bind_map, staging_root)
    if host_root is None:
        die(f"staging root {staging_root} is not under any bind in bind_map")
    gc_staging(staging_root, STAGING_TTL, now)
    uid = uuid.uuid4().hex[:16]
    src_dir = os.path.dirname(file_abs)
    dst_dir = os.path.join(staging_root, uid)
    if not copy_tree_capped(src_dir, dst_dir, max_files, max_bytes):
        # Over cap — file only (relative assets won't load; documented limit).
        shutil.rmtree(dst_dir, ignore_errors=True)
        os.makedirs(dst_dir, exist_ok=True)
        try:
            shutil.copy2(file_abs, os.path.join(dst_dir, os.path.basename(file_abs)))
        except OSError as e:
            die(f"staged copy of {file_abs} failed: {e}")
        sys.stderr.write(
            f"agtermctl: staged {file_abs} as file only "
            f"(tree exceeds {max_files} files / {max_bytes} bytes)\n"
        )
        sys.stderr.flush()
    manifest = load_manifest(staging_root)
    manifest[uid] = {
        "source_file": file_abs,
        "source_dir": src_dir,
        "time": now,
    }
    save_manifest(staging_root, manifest)
    staged_file = os.path.join(dst_dir, os.path.basename(file_abs))
    return staged_file, dst_dir


def recopy_staging(staging_root, max_files, max_bytes):
    """Reload support: re-copy every live manifest entry in place."""
    manifest = load_manifest(staging_root)
    for uid, row in manifest.items():
        dst_dir = os.path.join(staging_root, uid)
        src_dir = row.get("source_dir")
        src_file = row.get("source_file")
        if not src_dir or not src_file:
            continue
        if not copy_tree_capped(src_dir, dst_dir, max_files, max_bytes):
            try:
                os.makedirs(dst_dir, exist_ok=True)
                shutil.copy2(src_file, os.path.join(dst_dir, os.path.basename(src_file)))
            except OSError:
                pass
        # count a reloaded page as used, or gc sweeps a long-lived overlay's dir
        try:
            os.utime(dst_dir, None)
        except OSError:
            pass


def rewrite_url(url, hosts_map, expose_fn):
    """Rewrite container-loopback URL via expose_fn(port)->host_port.
    None ⇒ not loopback / not rewritable (passthrough)."""
    try:
        parts = urlsplit(url)
    except ValueError:
        return None
    if parts.scheme not in ("http", "https") or not parts.hostname:
        return None
    host = parts.hostname.lower()
    if host not in LOOPBACK_HOSTS and host not in hosts_map:
        return None
    try:
        port = parts.port
    except ValueError:
        return None
    if port is None:
        port = 443 if parts.scheme == "https" else 80
    host_port = expose_fn(port)
    return urlunsplit((parts.scheme, f"127.0.0.1:{host_port}",
                       parts.path, parts.query, parts.fragment))


def run_expose(port):
    """Run AGT_OVL_EXPOSE <port>; parse the stable reply line. Dies loudly —
    a silent passthrough would open the MAC's localhost: wrong server."""
    cmd = shlex.split(EXPOSE_CMD) + [str(port)]
    try:
        proc = subprocess.run(cmd, check=False, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError) as e:
        die(f"expose command failed for port {port}: {e}\n  command: {' '.join(cmd)}")
    if proc.returncode != 0:
        die(
            f"expose command exited {proc.returncode} for port {port}: "
            f"{proc.stderr.strip() or proc.stdout.strip()}"
        )
    for m in EXPOSE_LINE_RE.finditer(proc.stdout):
        if int(m.group(1)) == port:
            return int(m.group(2))
    die(f"could not parse expose reply for port {port}: {proc.stdout.strip()!r}")


# --- Receiver client ---------------------------------------------------------

def encode_request(request):
    """One JSON line: an argv passthrough or a structured op request."""
    return (json.dumps(request) + "\n").encode("utf-8")


def apply_frame(frame, out, err):
    """Apply one reply frame. Returns the exit code when terminal, else None."""
    kind = frame.get("t")
    if kind in ("out", "err"):
        data = base64.b64decode(frame.get("b", ""))
        (out if kind == "out" else err)(data)
        return None
    if kind == "rc":
        return frame.get("rc", 1)
    return None


def _write_out(data):
    sys.stdout.buffer.write(data)
    sys.stdout.buffer.flush()  # events streams live, not when the buffer fills


def _write_err(data):
    sys.stderr.buffer.write(data)
    sys.stderr.buffer.flush()


def run_remote(request, host, port):
    """Send one request to the receiver, stream output, return the exit code."""
    try:
        sock = socket.create_connection((host, port), timeout=30)
    except OSError as e:
        die(
            f"cannot reach the agtermctl receiver at {host}:{port}: {e}\n"
            "  start it on the Mac: agtermctl-receiver.py (see the recipe)"
        )
    with sock:
        sock.settimeout(None)  # --block holds the call for the overlay's life
        sock.sendall(encode_request(request))
        rc = None
        saw_err = False
        for line in sock.makefile("rb"):
            try:
                frame = json.loads(line)
            except ValueError:
                continue
            if frame.get("t") == "err":
                saw_err = True
            got = apply_frame(frame, _write_out, _write_err)
            if got is not None:
                rc = got
    if rc is None:
        die("receiver closed the connection without an exit code")
    if rc == 2 and not saw_err and request.get("op") == "exec":
        # A current receiver always explains a refusal in an err frame; a
        # bare rc 2 means the receiver predates the structured exec request.
        sys.stderr.write(
            "agtermctl: the receiver answered rc 2 without a reason — it predates the\n"
            "  structured exec request; update agtermctl-receiver.py (see the recipe)\n"
        )
        sys.stderr.flush()
    return rc


def agterm_env():
    """The AGTERM_* identity that crosses with every request."""
    return {k: v for k, v in os.environ.items() if k.startswith("AGTERM_") and v}


def passthrough(argv):
    debug(f"passthrough → receiver {RECEIVER_HOST}:{RECEIVER_PORT}")
    sys.exit(run_remote({"argv": list(argv), "env": agterm_env()},
                        RECEIVER_HOST, RECEIVER_PORT))


# --- Routing -----------------------------------------------------------------

ROUTE_OPEN = ["session", "overlay", "open"]
ROUTE_RELOAD = ["session", "overlay", "reload"]


def rewrite_open(argv, tokens_base, tokens, *, env, pwd, cname, info,
                 hosts_map, expose_fn, target_id=None):
    """Rewrite a routed `session overlay open` call.

    Returns an argv list — the input possibly rewritten, or unchanged for
    passthrough — or a dict: the structured exec request a COMMAND becomes
    (the receiver builds the docker-exec line on the Mac; no caller-written
    shell line crosses). `tokens` are argv[tokens_base:]; every parse_open
    index is relative to tokens and MUST be rebased by tokens_base before
    touching argv — a leading global flag (e.g. `agtermctl --json session
    overlay open …`) shifts everything. All dependencies are injected
    (selftest drives it with fakes).
    """
    call = parse_open(tokens)
    if call is None:
        if _has_page_flag(tokens):
            debug("open: unparsable with --html/--url → passthrough (host may know a newer flag)")
            return argv
        die(
            "session overlay open: unparsable call refused — sent as-is it would "
            "run its COMMAND on the Mac; the wrapper knows agterm 0.39.0's flag surface"
        )
    html = call.values.get("--html")
    url = call.values.get("--url")
    cwd = call.values.get("--cwd")
    has_cmd = call.command_idx is not None

    if has_cmd and (html or url):
        # Never succeeds host-side; dying locally keeps the receiver's
        # refusal for genuinely raw COMMANDs unambiguous.
        die(f"session.overlay.open takes a command or {'--html' if html else '--url'}, not both")
    if html and url:
        debug("open: --html and --url → passthrough (host CLI will error)")
        return argv

    # Session targeting: agtermctl defaults --target to the ACTIVE session,
    # so an overlay opened from a container lands on whatever terminal is
    # focused. The calling container's identity is AGTERM_SESSION_ID (passed
    # into the container at docker run) — inject --target when present and
    # the caller didn't pass one, on every open that parses.
    def inject_target():
        if target_id and "--target" not in call.values:
            argv[tokens_base:tokens_base] = ["--target", target_id]
            debug(f"open: --target {target_id} injected")

    def set_flag_value(flag, value):
        """Replace the value token of `flag` in argv, honoring --flag=value
        form. Returns True when a substitution was made."""
        for idx, fl in call.subst.items():
            if fl == flag:
                argv[tokens_base + idx] = (
                    f"{flag}={value}" if idx in call.eq_form else value
                )
                return True
        return False

    if has_cmd:
        if not cname:
            die("cannot resolve the container name via AGT_OVL_CONTAINER_SOURCE — the exec-back needs it")
        cwd_abs = pwd
        if cwd:
            cwd_abs = os.path.normpath(
                cwd if os.path.isabs(cwd) else os.path.join(pwd, cwd)
            )
        payload = build_payload(cwd_abs, tokens[call.command_idx])
        flags = slice_open_flags(tokens, call.command_idx)
        if target_id and "--target" not in call.values:
            flags += ["--target", target_id]
            debug(f"open: --target {target_id} injected")
        debug(f"open: COMMAND → op exec in {cname}")
        return {
            "op": "exec",
            "container": cname,
            "payload_b64": base64.b64encode(payload.encode("utf-8")).decode("ascii"),
            "global_flags": argv[:tokens_base - len(ROUTE_OPEN)],
            "flags": flags,
            "env": {k: v for k, v in env.items() if k.startswith("AGTERM_") and v},
        }

    if html:
        if info is None:
            # a known-dead passthrough: the host CLI cannot resolve a
            # container path (or worse, resolves an unrelated same-named one)
            die(f"no bind map at {BIND_MAP_SOURCE} — run bind-map.py (see the recipe)")
        bind_map, store_roots = info["bind_map"], info["store_roots"]
        file_abs = os.path.normpath(
            html if os.path.isabs(html) else os.path.join(pwd, html)
        )
        cwd_abs = None
        if cwd:
            cwd_abs = os.path.normpath(
                cwd if os.path.isabs(cwd) else os.path.join(pwd, cwd)
            )
        mode, a, b = decide_html(file_abs, cwd_abs, bind_map, store_roots)
        if mode == "direct":
            new_file, new_cwd = a, b
            debug(f"open: --html → {new_file} (grant {new_cwd})")
        else:
            now = int(time.time())
            staged_file, staged_dir = stage_page(
                STAGING_ROOT, bind_map, file_abs, STAGING_MAX_FILES,
                STAGING_MAX_BYTES, now,
            )
            new_file = translate(bind_map, staged_file)
            new_cwd = translate(bind_map, staged_dir)
            debug(f"open: --html staged → {new_file} (grant {new_cwd})")
        set_flag_value("--html", new_file)
        if "--cwd" in call.values:
            set_flag_value("--cwd", new_cwd)
        else:
            # Synthesize the grant right after the --html token — without
            # it agterm loads the page via loadHTMLString at about:blank
            # with zero file access (no relative assets).
            for idx, fl in call.subst.items():
                if fl == "--html":
                    pos = tokens_base + idx + 1
                    argv[pos:pos] = ["--cwd", new_cwd]
                    break
        inject_target()
        return argv

    if url:
        # inject_target splices at tokens_base and would shift the
        # substitution indices — substitute first, inject last (as in the
        # html branch); the passthrough paths inject on their way out.
        if expose_fn is not None:
            new_url = rewrite_url(url, hosts_map, expose_fn)
            if new_url is not None:
                set_flag_value("--url", new_url)
                inject_target()
                debug(f"open: --url → {new_url}")
                return argv
        inject_target()  # every parsed URL open targets the caller's session
        debug("open: --url passthrough (not rewritten or rewriting disabled)")
        return argv

    # Bare `overlay open` with neither COMMAND nor --html/--url: host CLI
    # errors — passthrough keeps the error identical.
    return argv


def main():
    argv = sys.argv[1:]
    if os.environ.get("AGT_OVL_SELFTEST") == "1":
        suite = unittest.TestLoader().loadTestsFromTestCase(T)
        result = unittest.TextTestRunner(verbosity=2).run(suite)
        sys.exit(0 if result.wasSuccessful() else 1)

    # The calling container's session identity (passed into the container at
    # docker run from the agterm shell that started it) — routes overlay
    # calls to the right session.
    sid = os.environ.get("AGTERM_SESSION_ID") or None

    tokens_base, rest = find_route(argv, ROUTE_OPEN)
    if tokens_base is not None:
        out = rewrite_open(
            list(argv), tokens_base, rest,
            env=agterm_env(), pwd=os.getcwd(), cname=container_name(),
            info=load_info(), hosts_map=load_hosts_loopback(),
            expose_fn=run_expose if EXPOSE_CMD else None, target_id=sid,
        )
        if isinstance(out, dict):
            sys.exit(run_remote(out, RECEIVER_HOST, RECEIVER_PORT))
        passthrough(out)

    reload_base, reload_rest = find_route(argv, ROUTE_RELOAD)
    if reload_base is not None:
        recopy_staging(STAGING_ROOT, STAGING_MAX_FILES, STAGING_MAX_BYTES)
        if sid and not any(
            t == "--target" or t.startswith("--target=") for t in reload_rest
        ):
            argv = list(argv)
            argv[reload_base:reload_base] = ["--target", sid]
            debug(f"reload: --target {sid} injected")
        debug("reload: re-copied live staging entries")
        passthrough(argv)
    passthrough(argv)


