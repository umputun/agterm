            os.makedirs(os.path.join(src, "sub"))
            for i in range(5):
                with open(os.path.join(src, f"f{i}.txt"), "w") as f:
                    f.write("x" * 10)
            with open(os.path.join(src, "sub", "g.txt"), "w") as f:
                f.write("y" * 10)
            dst = os.path.join(tmp, "dst")
            self.assertTrue(copy_tree_capped(src, dst, 100, 10000))
            self.assertTrue(os.path.exists(os.path.join(dst, "sub", "g.txt")))
            dst2 = os.path.join(tmp, "dst2")
            self.assertFalse(copy_tree_capped(src, dst2, 3, 10000))
            self.assertFalse(os.path.exists(dst2))  # nothing copied on cap

            # GC: an old uuid dir goes, a fresh one stays, manifest follows.
            staging = os.path.join(tmp, "staging")
            os.makedirs(os.path.join(staging, "olduuid"))
            os.makedirs(os.path.join(staging, "newuuid"))
